/* Onix Lunar Corp — site behaviour.
   Every number comes from window.SITE_DATA (generated by `lunar-gun generate site`).
   This file adds no numbers of its own. */

(function () {
  "use strict";

  /* Set this to a form endpoint (for example a Formspree URL) if the site is not
     hosted on Netlify. Netlify Forms needs no endpoint. */
  var FORM_ENDPOINT = "";

  var data = window.SITE_DATA || {};
  var reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  function get(path) {
    return path.split(".").reduce(function (node, key) {
      return node == null ? null : node[key];
    }, data);
  }

  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text != null) node.textContent = text;
    return node;
  }

  /* ── Bind single values ─────────────────────────────────── */

  document.querySelectorAll("[data-bind]").forEach(function (node) {
    var value = get(node.getAttribute("data-bind"));
    if (value != null) node.textContent = value;
  });

  /* ── Stat strip ─────────────────────────────────────────── */

  var strip = document.getElementById("stat-strip");
  (get("stats") || []).forEach(function (stat, i) {
    var li = el("li", "reveal");
    li.style.setProperty("--d", i * 80 + "ms");
    li.appendChild(el("span", "stat-label", stat.label));
    li.appendChild(el("span", "stat-value", stat.value));
    li.appendChild(el("span", "stat-unit", stat.unit));
    strip.appendChild(li);
  });

  /* ── Velocity bars ──────────────────────────────────────── */

  var bars = document.getElementById("velocity-bars");
  [
    { key: "velocity.earth", primary: false },
    { key: "velocity.moon", primary: true },
  ].forEach(function (row, i) {
    var item = get(row.key);
    if (!item) return;

    var wrap = el("div", "bar reveal" + (row.primary ? " is-primary" : ""));
    wrap.style.setProperty("--d", i * 120 + "ms");

    var head = el("div", "bar-head");
    head.appendChild(el("span", "bar-label", item.label));

    var value = el("span", "bar-value", item.value);
    value.appendChild(el("small", null, "km/s"));
    head.appendChild(value);
    wrap.appendChild(head);

    var track = el("div", "bar-track");
    var fill = el("span", "bar-fill");
    fill.dataset.width = Math.round(item.fraction * 100) + "%";
    track.appendChild(fill);
    wrap.appendChild(track);
    wrap.appendChild(el("p", "bar-note", item.note));
    bars.appendChild(wrap);
  });

  /* ── Spec sheet ─────────────────────────────────────────── */

  var specs = document.getElementById("spec-sheet");
  (get("specs") || []).forEach(function (spec, i) {
    var row = el("div", "spec-row reveal");
    row.style.setProperty("--d", (i % 5) * 60 + "ms");
    row.appendChild(el("dt", null, spec.label));
    row.appendChild(el("dd", null, spec.value));
    specs.appendChild(row);
  });

  /* ── Customer segments ──────────────────────────────────── */

  var segments = document.getElementById("segments");
  (get("segments") || []).forEach(function (segment, i) {
    var li = el("li", "reveal");
    li.style.setProperty("--d", i * 90 + "ms");
    li.insertAdjacentHTML(
      "afterbegin",
      '<svg viewBox="0 0 16 16" aria-hidden="true"><path d="M2 8h11M9 4l4 4-4 4"/></svg>'
    );
    li.appendChild(el("span", null, segment.label));
    segments.appendChild(li);
  });

  /* ── Reveal on scroll ───────────────────────────────────── */

  var revealables = document.querySelectorAll(".reveal");

  if (reduced || !("IntersectionObserver" in window)) {
    revealables.forEach(function (node) {
      node.classList.add("is-in");
    });
    document.querySelectorAll(".bar-fill").forEach(function (fill) {
      fill.style.width = fill.dataset.width;
    });
  } else {
    var observer = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (!entry.isIntersecting) return;
          entry.target.classList.add("is-in");
          var fill = entry.target.querySelector(".bar-fill");
          if (fill) fill.style.width = fill.dataset.width;
          observer.unobserve(entry.target);
        });
      },
      { rootMargin: "0px 0px -6% 0px", threshold: 0.08 }
    );
    revealables.forEach(function (node) {
      observer.observe(node);
    });
  }

  /* ── Header state and scroll rail ───────────────────────── */

  var header = document.getElementById("site-header");
  var rail = document.getElementById("scroll-progress");
  var ticking = false;

  function onScroll() {
    var top = window.scrollY || 0;
    header.classList.toggle("is-stuck", top > 24);
    var span = document.documentElement.scrollHeight - window.innerHeight;
    rail.style.width = (span > 0 ? (top / span) * 100 : 0) + "%";
    ticking = false;
  }

  window.addEventListener(
    "scroll",
    function () {
      if (ticking) return;
      ticking = true;
      window.requestAnimationFrame(onScroll);
    },
    { passive: true }
  );
  onScroll();

  /* ── Contact form ───────────────────────────────────────── */

  var form = document.getElementById("contact-form");
  var note = document.getElementById("form-note");
  var button = form.querySelector("button[type=submit]");
  var restingHtml = note.innerHTML;

  function setNote(text, state) {
    if (state == null) {
      note.innerHTML = restingHtml;
    } else {
      note.textContent = text;
    }
    note.classList.toggle("is-error", state === "error");
    note.classList.toggle("is-done", state === "done");
  }

  function invalidField() {
    var fields = form.querySelectorAll("input[required], textarea[required]");
    for (var i = 0; i < fields.length; i++) {
      var field = fields[i];
      var bad = !field.value.trim() || (field.type === "email" && !field.checkValidity());
      field.setAttribute("aria-invalid", bad ? "true" : "false");
      if (bad) return field;
    }
    return null;
  }

  form.addEventListener("submit", function (event) {
    event.preventDefault();

    var bad = invalidField();
    if (bad) {
      setNote("Check the marked field.", "error");
      bad.focus();
      return;
    }

    button.disabled = true;
    setNote("Sending.");

    var payload = new FormData(form);
    var target = FORM_ENDPOINT || window.location.pathname;

    fetch(target, { method: "POST", body: payload, headers: { Accept: "application/json" } })
      .then(function (response) {
        if (!response.ok) throw new Error(String(response.status));
        form.reset();
        setNote("Message sent. We answer every message.", "done");
      })
      .catch(function () {
        setNote("Send failed. Try again later.", "error");
      })
      .finally(function () {
        button.disabled = false;
        window.setTimeout(function () {
          if (!note.classList.contains("is-done")) setNote();
        }, 6000);
      });
  });

  /* ── Footer year ────────────────────────────────────────── */

  document.getElementById("year").textContent = String(new Date().getFullYear());
})();
